#!/usr/bin/env python3
"""Create first-pass cards for IMO Shortlist C-problems with central graph use.

The cards are intentionally compact: official solutions are translated and
compressed, while deeper alternative-solution and relation searches are left for
later passes.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
TODAY = date.today().isoformat()


def dump(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def status() -> dict[str, str]:
    return {"status": "ai_checked"}


def stmt(text: str, source_id: str, title: str = "Условие") -> dict[str, object]:
    return {
        "id": "stmt-original",
        "title": title,
        "text": text,
        "source_id": source_id,
        "status": "needs_human_review",
        "self_contained": status(),
        "definition_ids": [],
    }


def graph_stmt(text: str) -> dict[str, object]:
    return {
        "id": "stmt-graph",
        "text": text,
        "status": "needs_human_review",
        "self_contained": status(),
        "definition_ids": [],
        "distinct_from": ["stmt-original"],
    }


def idea(i: str, title: str, text: str, tags: list[str]) -> dict[str, object]:
    return {"id": i, "title": title, "text": text, "tags": tags, "status": "needs_human_review"}


def solution(title: str, text: str, idea_ids: list[str], standard_idea_ids: list[str]) -> dict[str, object]:
    return {
        "id": "sol-official-compressed",
        "title": title,
        "text": text,
        "idea_ids": idea_ids,
        "standard_idea_ids": standard_idea_ids,
        "status": "needs_human_review",
    }


def card(
    pid: str,
    title: str,
    year: int,
    shortlist_id: str,
    country: str,
    statement: str,
    graph_statement: str | None,
    ideas: list[dict[str, object]],
    sol_text: str,
    profile: dict[str, list[str]],
    tags: list[str],
    difficulty: str = "imo_p3_plus",
) -> dict[str, object]:
    source_id = f"src-imo-{year}-shortlist"
    secondary = ["application"] if graph_statement else ["graph_in_solution", "application"]
    editorial: dict[str, object] = {
        "created_by": "ai",
        "created_at": TODAY,
        "review_status": "needs_human_review",
        "public_ready": False,
        "notes": [
            "Карточка создана в первом проходе по официальному IMO Shortlist; решения сжаты, альтернативные решения и глубокие связи пока не искались."
        ],
    }
    if not graph_statement:
        editorial["graph_theory_absent_reason"] = (
            "Графовая структура используется в официальном решении, но не является самостоятельной переформулировкой исходного условия."
        )
    original = stmt(statement, source_id)
    if graph_statement:
        original["distinct_from"] = ["stmt-graph"]
    return {
        "id": pid,
        "title": title,
        "kind": {"primary": "olympiad_problem", "secondary": secondary},
        "language": "ru",
        "problem_profile": {
            **profile,
            "keywords": [f"imo_{year}_{shortlist_id.lower()}", "imo_shortlist", "official_solution_graph"],
            "status": "needs_human_review",
        },
        "statements": {
            "original": [original],
            "graph_theory": [graph_stmt(graph_statement)] if graph_statement else [],
            "olympiad_reformulations": [],
        },
        "ideas": ideas,
        "solutions": [solution("Сжатое официальное решение", sol_text, [x["id"] for x in ideas], ["induction"] if "induction" in profile.get("methods", []) else [])],
        "difficulty": {
            "main": difficulty,
            "local_score": 12,
            "comment": f"IMO Shortlist {year} {shortlist_id}, {country}; графовый слой существенен в официальном решении.",
            "status": "needs_human_review",
        },
        "tags": tags,
        "properties": {"central_method": {"value": profile.get("methods", []), "status": "needs_human_review"}},
        "sources": [{"source_id": source_id, "role": "problem_and_solutions_official", "status": "source_verified"}],
        "editorial": editorial,
    }


